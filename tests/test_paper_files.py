"""docs/papers.md and docs/papers.zh-CN.md hold every paper line; each README keeps the newest papers and one
link per topic into its paper file, and `build_readme.py --check` covers all four files."""
from contextlib import redirect_stderr, redirect_stdout
import io
from pathlib import Path
import re
import shutil
import sys
from tempfile import TemporaryDirectory
import unittest
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
import build_readme
from build_paper_pages import papers_newest_first
from build_readme import (CASE_FILES, PAPER_FILES, PAPERS_BEGIN, PAPERS_END, READMES, RECENT_PAPERS, paper_line, paper_section,
                          render_paper_file)
from validate import markdown_anchors
from validate_papers import read_papers


def entry_lines(text):
    return [line for line in text.splitlines() if line.startswith('- [**')]


def readme_block(language):
    text = (ROOT / READMES[language]).read_text(encoding='utf-8')
    return text.split(PAPERS_BEGIN + '\n', 1)[1].split(PAPERS_END, 1)[0]


class PaperFileTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.papers = read_papers(ROOT)
        cls.files = {language: (ROOT / name).read_text(encoding='utf-8') for language, name in PAPER_FILES.items()}

    def test_paper_files_are_the_generated_output(self):
        for language, name in PAPER_FILES.items():
            with self.subTest(file=name):
                text = self.files[language]
                self.assertEqual(text, render_paper_file(self.papers, language))
                self.assertTrue(text.startswith(PAPERS_BEGIN + '\n<!-- Generated by scripts/build_readme.py from '
                                                'data/papers.json. Edit the source data and rerun the script; '
                                                'do not edit this file by hand. -->\n# '), text[:300])
                self.assertTrue(text.endswith(PAPERS_END + '\n'))

    def test_every_paper_appears_exactly_once_in_each_paper_file(self):
        for language, text in self.files.items():
            prefix = 'zh/' if language == 'zh' else ''
            lines = entry_lines(text)
            with self.subTest(file=PAPER_FILES[language]):
                self.assertEqual(len(lines), len(self.papers))
                for paper in self.papers:
                    self.assertEqual(text.count(f'](https://awesomerea.org/{prefix}papers/{paper["id"]}/)'), 1, paper['id'])
                    self.assertEqual(lines.count(paper_line(paper, language)), 1, paper['id'])

    def test_each_topic_keeps_its_anchor_heading_and_newest_first_order(self):
        for language, text in self.files.items():
            with self.subTest(file=PAPER_FILES[language]):
                sections = re.findall(r'^<a id="papers-([a-z-]+)"></a>\n## (.+)$', text, re.MULTILINE)
                expected = [section for section in build_readme.PAPER_SECTIONS
                            if any(paper_section(paper) == section for paper in self.papers)]
                self.assertEqual([section for section, _ in sections], expected)
                for section, heading in sections:
                    self.assertEqual(heading, build_readme.PAPER_SECTIONS[section][language == 'zh'])
                    body = text.split(f'<a id="papers-{section}"></a>\n', 1)[1].split('<a id="papers-', 1)[0]
                    group = [paper for paper in self.papers if paper_section(paper) == section]
                    self.assertEqual(entry_lines(body), [paper_line(paper, language) for paper in papers_newest_first(group)])

    def test_readme_lists_the_newest_papers_exactly_as_the_paper_file_does(self):
        newest = papers_newest_first(self.papers)[:RECENT_PAPERS]
        for language, name in READMES.items():
            lines = entry_lines(readme_block(language))
            with self.subTest(readme=name):
                self.assertEqual(len(lines), RECENT_PAPERS)
                self.assertEqual(lines, [paper_line(paper, language) for paper in newest])
                listed = entry_lines(self.files[language])
                for line in lines:
                    self.assertIn(line, listed)

    def test_readme_topic_links_resolve_to_anchors_in_the_paper_file(self):
        topics = {paper_section(paper) for paper in self.papers}
        for language, name in READMES.items():
            block = readme_block(language)
            anchors = markdown_anchors(self.files[language])
            links = re.findall(r'\]\((docs/papers[\w.-]*\.md)#([^)\s]+)\)', block)
            with self.subTest(readme=name):
                self.assertEqual(sorted(fragment for _, fragment in links), sorted(f'papers-{topic}' for topic in topics))
                for target, fragment in links:
                    self.assertEqual(target, PAPER_FILES[language])
                    self.assertIn(fragment, anchors)
                # The links line opens the paper file itself, and the website's paper directory.
                self.assertIn(f']({PAPER_FILES[language]}) · ', block)
                self.assertIn(f"](https://awesomerea.org/{'zh/' if language == 'zh' else ''}papers/) · ", block)

    def test_paper_files_link_back_to_the_readme_and_to_each_other(self):
        for language, text in self.files.items():
            other = 'papers.md' if language == 'zh' else 'papers.zh-CN.md'
            with self.subTest(file=PAPER_FILES[language]):
                navigation = text.split('\n# ', 1)[1].split('\n\n', 2)[1]
                self.assertIn(f'](../{READMES[language]}#papers)', navigation)
                self.assertIn(f']({other})', navigation)
                anchors = markdown_anchors(text)
                fragments = re.findall(r'\]\(#([^)\s]+)\)', text)
                # The topic Contents list plus one link back to it under each topic.
                self.assertGreaterEqual(len(fragments), 2 * len({paper_section(paper) for paper in self.papers}))
                for fragment in fragments:
                    self.assertIn(fragment, anchors)
                self.assertIn('papers', markdown_anchors((ROOT / READMES[language]).read_text(encoding='utf-8')))

    def test_contributor_docs_list_both_paper_files_as_generated(self):
        for path, label in (('CONTRIBUTING.md', '- **Generated files:**'), ('CONTRIBUTING.zh-CN.md', '- **生成文件**'),
                            ('AGENTS.md', '- Never edit generated')):
            text = (ROOT / path).read_text(encoding='utf-8')
            line = next(line for line in text.splitlines() if line.startswith(label))
            with self.subTest(path=path):
                for name in PAPER_FILES.values():
                    self.assertIn(f'`{name}`', line)
                if path.startswith('CONTRIBUTING'):
                    self.assertIn('docs/cases.md', line)

    def test_check_fails_when_a_paper_file_is_stale_or_missing(self):
        # Contents carries the repository index count; reuse the README's own so only paper files can drift.
        index_count = int(re.search(r'\[Full Repository Index\]\(#full-repository-index\) \(([\d,]+)\)',
                                    (ROOT / 'README.md').read_text(encoding='utf-8'))[1].replace(',', ''))
        with TemporaryDirectory() as temporary:
            root = Path(temporary)
            for directory in ('data', 'docs', 'site'):
                (root / directory).mkdir()
            for name in ('data/papers.json', 'site/translations.zh-CN.json', *READMES.values(), *PAPER_FILES.values(), *CASE_FILES.values()):
                shutil.copyfile(ROOT / name, root / name)

            def run(*arguments):
                stdout, stderr = io.StringIO(), io.StringIO()
                with patch.object(build_readme, 'ROOT', root), \
                        patch.object(build_readme, 'browsable_index_count', return_value=index_count), \
                        patch.object(sys, 'argv', ['build_readme.py', *arguments]), \
                        redirect_stdout(stdout), redirect_stderr(stderr):
                    return build_readme.main(), stderr.getvalue()

            status, errors = run('--check')
            self.assertEqual(status, 0)
            self.assertNotIn('Stale generated files', errors)
            (root / PAPER_FILES['en']).write_text(self.files['en'].replace('## Contents', '## Contents edited'),
                                                  encoding='utf-8')
            (root / PAPER_FILES['zh']).unlink()
            status, errors = run('--check')
            self.assertEqual(status, 1)
            self.assertIn('Stale generated files: docs/papers.md, docs/papers.zh-CN.md\n', errors)
            # Rebuilding restores both files, including a missing docs/ directory.
            shutil.rmtree(root / 'docs')
            self.assertEqual(run()[0], 0)
            for language, name in PAPER_FILES.items():
                self.assertEqual((root / name).read_text(encoding='utf-8'), self.files[language])
            status, errors = run('--check')
            self.assertEqual(status, 0)
            self.assertNotIn('Stale generated files', errors)


if __name__ == '__main__':
    unittest.main()
