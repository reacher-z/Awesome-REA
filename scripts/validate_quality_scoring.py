#!/usr/bin/env python3
"""Validate the quality-evaluation candidate and result datasets.

These two files are a first-class dataset, not scratch output:

- data/evaluation-candidates.json is a manual input list. Candidates are not
  curated catalog records and never render on the site.
- data/quality-evaluations.json is generated by scripts/quality_scoring.py.
  It must not be edited by hand; the validator recomputes every score from
  the recorded rule results and rejects an inconsistent file.

Both files are optional as a pair. A repository without quality data passes;
a repository with only one of them fails.
"""
from __future__ import annotations

import datetime as dt
import json
import re
from pathlib import Path

# Kept in sync with scripts/quality_scoring.py. PR-0 lands before the scorer,
# so this validator cannot import the scorer module yet.
DIMENSIONS = {
    "artifact_integrity", "functional_coverage", "correctness", "performance",
    "security_isolation", "ui_consistency", "persistence_recovery", "concurrency",
    "file_formats", "reproducibility",
}
LEVELS = (
    "L0-evidence", "L1-source-static", "L2-artifact-static",
    "L3-runtime-smoke", "L4-functional-rules", "L5-full-quality",
)
LEVEL_WEIGHT = {
    "L0-evidence": 0.0, "L1-source-static": 0.2, "L2-artifact-static": 0.4,
    "L3-runtime-smoke": 0.6, "L4-functional-rules": 1.0, "L5-full-quality": 1.0,
}

SPEC_VERSION = "quality-eval-v1"
CANDIDATE_SPEC = "evaluation-candidates-v1"
TARGETS = {"website", "game", "app", "binary", "firmware", "protocol"}
KINDS = {"case-study", "project", "tool", "integration"}
RELATIONSHIPS = {
    "official-core", "official-skill", "official-documentation", "official-guide",
    "official-case-study", "community-integration", "community-learning-resource",
    "community-reported-mixed-workflow", "upstream-maintainer-companion-list",
    "independent-agent-integration", "independent-reconstruction", "foundation", "learning",
}
STATUSES = {"pass", "fail", "blocked", "partial", "error"}
DIMENSION_STATUSES = {"pass", "fail", "blocked", "partial", "not-tested"}
VERDICTS = {"verified", "artifact-verified", "source-inspected", "partially-verified",
            "failed", "blocked", "ungraded"}
ID_PATTERN = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")

CANDIDATE_KEYS = {
    "id", "name", "url", "category", "relationship", "description_en", "description_zh",
    "evidence_url", "verified_at", "verification", "requirements", "targets", "kind",
    "source_index_id", "selection_reason", "evidence",
}
EVALUATION_KEYS = {"id", "url", "profile", "route", "results", "score", "limitations", "evidence_files"}
PROFILE_KEYS = {
    "entry_id", "url", "name", "catalog_status", "kind", "targets", "category", "software",
    "evidence_class", "source", "docs", "demo", "artifacts", "interfaces", "sandbox", "rule_pack",
}
ROUTE_KEYS = {"level", "tools", "blocked", "reason"}
SCORE_KEYS = {
    "score", "formula", "level_weight", "quality_fraction", "coverage", "pass_rate",
    "all_applicable_pass", "verdict", "counts", "dimensions",
}
COUNT_KEYS = {"passed", "failed", "blocked", "evaluated_dimensions", "applicable_dimensions"}


def load_json(path: Path, errors: list[str]) -> dict:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        errors.append(f"{path.name}: cannot read JSON ({error})")
        return {}


def iso_date(value: object) -> bool:
    if not isinstance(value, str):
        return False
    try:
        dt.date.fromisoformat(value)
    except ValueError:
        return False
    return True


def iso_datetime(value: object) -> bool:
    if not isinstance(value, str):
        return False
    try:
        dt.datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError:
        return False
    return True


def validate_candidates(document: dict, curated_ids: set[str]) -> list[str]:
    errors: list[str] = []
    if set(document) != {"schema_version", "meta", "entries"}:
        errors.append("evaluation-candidates.json: top-level keys must be schema_version, meta, entries")
    if document.get("schema_version") != 1:
        errors.append("evaluation-candidates.json: schema_version must be 1")
    meta = document.get("meta")
    if not isinstance(meta, dict) or set(meta) != {"spec", "purpose", "updated_at"}:
        errors.append("evaluation-candidates.json: meta must have exactly spec, purpose, updated_at")
    else:
        if meta.get("spec") != CANDIDATE_SPEC:
            errors.append(f"evaluation-candidates.json: meta.spec must be {CANDIDATE_SPEC}")
        if not isinstance(meta.get("purpose"), str) or not meta["purpose"].strip():
            errors.append("evaluation-candidates.json: meta.purpose must be nonempty")
        if not iso_date(meta.get("updated_at")):
            errors.append("evaluation-candidates.json: meta.updated_at must be YYYY-MM-DD")
    entries = document.get("entries")
    if not isinstance(entries, list):
        return errors + ["evaluation-candidates.json: entries must be a list"]
    seen: set[str] = set()
    for index, entry in enumerate(entries):
        label = f"evaluation-candidates.json entries[{index}]"
        if not isinstance(entry, dict):
            errors.append(f"{label}: must be an object")
            continue
        if set(entry) != CANDIDATE_KEYS:
            unknown = sorted(set(entry) - CANDIDATE_KEYS)
            missing = sorted(CANDIDATE_KEYS - set(entry))
            errors.append(f"{label}: keys differ (missing={missing}, unknown={unknown})")
            continue
        entry_id = entry["id"]
        if not isinstance(entry_id, str) or not ID_PATTERN.fullmatch(entry_id):
            errors.append(f"{label}: id must be a lowercase hyphenated slug")
        elif entry_id in seen:
            errors.append(f"{label}: duplicate id {entry_id}")
        elif entry_id in curated_ids:
            errors.append(f"{label}: id {entry_id} duplicates a curated catalog record")
        seen.add(entry_id)
        for key in ("name", "category", "relationship", "description_en", "description_zh",
                    "evidence_url", "selection_reason"):
            if not isinstance(entry[key], str) or not entry[key].strip():
                errors.append(f"{label}: {key} must be nonempty text")
        if entry["relationship"] not in RELATIONSHIPS:
            errors.append(f"{label}: unknown relationship {entry['relationship']!r}")
        if entry["kind"] not in KINDS:
            errors.append(f"{label}: unknown kind {entry['kind']!r}")
        if not isinstance(entry["targets"], list) or not entry["targets"]:
            errors.append(f"{label}: targets must be a nonempty list")
        elif not set(entry["targets"]) <= TARGETS:
            errors.append(f"{label}: unknown targets {sorted(set(entry['targets']) - TARGETS)}")
        if entry["verification"] != "source-reviewed":
            errors.append(f"{label}: verification must be source-reviewed")
        if not iso_date(entry["verified_at"]):
            errors.append(f"{label}: verified_at must be YYYY-MM-DD")
        if not isinstance(entry["requirements"], list) or not entry["requirements"] or not all(
                isinstance(item, str) and item.strip() for item in entry["requirements"]):
            errors.append(f"{label}: requirements must be a nonempty list of nonempty strings")
        if not isinstance(entry["source_index_id"], str) or not entry["source_index_id"].startswith("scan-"):
            errors.append(f"{label}: source_index_id must name a scan record")
        for key in ("url", "evidence_url"):
            if not isinstance(entry[key], str) or not entry[key].startswith("https://"):
                errors.append(f"{label}: {key} must be an HTTPS URL")
        evidence = entry["evidence"]
        if not isinstance(evidence, dict) or set(evidence) != {"evidence_class", "basis", "evidence_status", "signals"}:
            errors.append(f"{label}: evidence must have exactly evidence_class, basis, evidence_status, signals")
            continue
        if evidence["evidence_status"] not in {"observed", "unknown"}:
            errors.append(f"{label}: evidence.evidence_status must be observed or unknown")
        if not isinstance(evidence["basis"], str) or not evidence["basis"].strip():
            errors.append(f"{label}: evidence.basis must be nonempty")
        signals = evidence["signals"]
        required_signals = {
            "code", "code_basis", "docs", "docs_bytes", "docs_full", "download", "download_links",
            "release_count", "release_asset_count", "demo", "media_count", "archived", "unavailable",
        }
        if not isinstance(signals, dict) or not required_signals <= set(signals):
            errors.append(f"{label}: evidence.signals is missing required keys")
        else:
            for key in ("code", "docs", "docs_full", "archived", "unavailable"):
                if not isinstance(signals[key], bool):
                    errors.append(f"{label}: signals.{key} must be boolean")
            for key in ("docs_bytes", "release_count", "release_asset_count", "media_count"):
                if not isinstance(signals[key], int) or signals[key] < 0:
                    errors.append(f"{label}: signals.{key} must be a nonnegative integer")
            for key in ("download_links", "demo"):
                if not isinstance(signals[key], list):
                    errors.append(f"{label}: signals.{key} must be a list")
    return errors


def recompute_dimensions(results: list[dict], dimensions: dict) -> tuple[dict, list[str]]:
    errors: list[str] = []
    grouped: dict[str, list[dict]] = {}
    for result in results:
        grouped.setdefault(result["dimension"], []).append(result)
    computed = {}
    values = {"pass": 1.0, "partial": 0.5, "fail": 0.0, "blocked": 0.0, "error": 0.0}
    for dimension in dimensions:
        items = grouped.get(dimension, [])
        statuses = [item["status"] for item in items]
        if not items:
            status = "not-tested"
        elif "fail" in statuses:
            status = "fail"
        elif all(status == "pass" for status in statuses):
            status = "pass"
        elif "blocked" in statuses or "error" in statuses:
            status = "blocked"
        else:
            status = "partial"
        fraction = (sum(values.get(item["status"], 0.0) for item in items) / len(items)) if items else 0.0
        computed[dimension] = {"status": status, "fraction": round(fraction, 3)}
        recorded = dimensions[dimension]
        if not isinstance(recorded, dict) or set(recorded) != {"status", "fraction", "rules"}:
            errors.append(f"score.dimensions.{dimension}: keys must be status, fraction, rules")
            continue
        if recorded["status"] != status:
            errors.append(f"score.dimensions.{dimension}: status {recorded['status']!r} != recomputed {status!r}")
        if abs(float(recorded["fraction"]) - round(fraction, 3)) > 1e-9:
            errors.append(f"score.dimensions.{dimension}: fraction differs from recomputed {fraction:.3f}")
        if not isinstance(recorded["rules"], list):
            errors.append(f"score.dimensions.{dimension}: rules must be a list")
    for dimension in grouped:
        if dimension not in dimensions:
            errors.append(f"score.dimensions: missing result dimension {dimension}")
    return computed, errors


def validate_score(entry: dict) -> list[str]:
    errors: list[str] = []
    score = entry["score"]
    if not isinstance(score, dict) or set(score) != SCORE_KEYS:
        return ["score: keys must be " + ", ".join(sorted(SCORE_KEYS))]
    route = entry["route"]
    level = route.get("level")
    if level not in LEVELS:
        errors.append(f"route.level: unknown level {level!r}")
        weight = 0.0
    else:
        weight = LEVEL_WEIGHT[level]
    if score["formula"] != "100 * mean(dimension_fraction) * level_weight":
        errors.append("score.formula: unexpected formula")
    if abs(float(score["level_weight"]) - weight) > 1e-9:
        errors.append("score.level_weight: does not match route.level")
    dimensions = score["dimensions"]
    if not isinstance(dimensions, dict) or not dimensions:
        return errors + ["score.dimensions must be a nonempty object"]
    for dimension in dimensions:
        if dimension not in DIMENSIONS:
            errors.append(f"score.dimensions: unknown dimension {dimension!r}")
    results = entry["results"]
    if not isinstance(results, list):
        return errors + ["results must be a list"]
    for result in results:
        if not isinstance(result, dict):
            errors.append("results: every item must be an object")
            continue
        if not isinstance(result.get("id"), str) or not result["id"]:
            errors.append("results: id must be nonempty text")
        if result.get("dimension") not in DIMENSIONS:
            errors.append(f"results: unknown dimension {result.get('dimension')!r}")
        if result.get("status") not in STATUSES:
            errors.append(f"results: unknown status {result.get('status')!r}")
    computed, dimension_errors = recompute_dimensions(results, dimensions)
    errors += dimension_errors
    counts = score["counts"]
    if not isinstance(counts, dict) or set(counts) != COUNT_KEYS:
        return errors + ["score.counts: keys must be " + ", ".join(sorted(COUNT_KEYS))]
    if counts["passed"] != sum(1 for result in results if result.get("status") == "pass"):
        errors.append("score.counts.passed: does not match results")
    if counts["failed"] != sum(1 for result in results if result.get("status") == "fail"):
        errors.append("score.counts.failed: does not match results")
    if counts["blocked"] != sum(1 for result in results if result.get("status") in {"blocked", "error"}):
        errors.append("score.counts.blocked: does not match results")
    evaluated = sum(1 for item in dimensions.values() if item.get("status") in {"pass", "fail", "partial"})
    if counts["evaluated_dimensions"] != evaluated:
        errors.append("score.counts.evaluated_dimensions: does not match dimensions")
    if counts["applicable_dimensions"] != len(dimensions):
        errors.append("score.counts.applicable_dimensions: does not match dimensions")
    quality_fraction = sum(computed[dimension]["fraction"] for dimension in dimensions) / len(dimensions)
    coverage = evaluated / len(dimensions)
    denominator = counts["passed"] + counts["failed"]
    pass_rate = counts["passed"] / denominator if denominator else None
    if abs(float(score["quality_fraction"]) - round(quality_fraction, 3)) > 1e-9:
        errors.append("score.quality_fraction: does not match dimension fractions")
    if abs(float(score["coverage"]) - round(coverage, 3)) > 1e-9:
        errors.append("score.coverage: does not match dimensions")
    if pass_rate is None:
        if score["pass_rate"] is not None:
            errors.append("score.pass_rate: must be null when no pass/fail rule ran")
    elif score["pass_rate"] is None or abs(float(score["pass_rate"]) - round(pass_rate, 3)) > 1e-9:
        errors.append("score.pass_rate: does not match results")
    expected_score = round(100 * quality_fraction * weight, 1) if denominator else None
    if expected_score is None:
        if score["score"] is not None:
            errors.append("score.score: must be null when no pass/fail rule ran")
    elif score["score"] is None or abs(float(score["score"]) - expected_score) > 1e-9:
        errors.append(f"score.score: expected {expected_score}, got {score['score']!r}")
    all_pass = all(item.get("status") == "pass" for item in dimensions.values())
    if score["all_applicable_pass"] is not all_pass:
        errors.append("score.all_applicable_pass: does not match dimensions")
    if counts["failed"]:
        expected_verdict = "failed"
    elif expected_score is not None and all_pass and level in {"L4-functional-rules", "L5-full-quality"}:
        expected_verdict = "verified"
    elif expected_score is not None and all_pass and level == "L2-artifact-static":
        expected_verdict = "artifact-verified"
    elif expected_score is not None and all_pass and level == "L1-source-static":
        expected_verdict = "source-inspected"
    elif expected_score is not None:
        expected_verdict = "partially-verified"
    elif counts["blocked"]:
        expected_verdict = "blocked"
    else:
        expected_verdict = "ungraded"
    if score["verdict"] not in VERDICTS:
        errors.append(f"score.verdict: unknown value {score['verdict']!r}")
    elif score["verdict"] != expected_verdict:
        errors.append(f"score.verdict: expected {expected_verdict}, got {score['verdict']!r}")
    return errors


def validate_evaluations(document: dict, known_ids: set[str]) -> list[str]:
    errors: list[str] = []
    if set(document) != {"schema_version", "meta", "entries"}:
        errors.append("quality-evaluations.json: top-level keys must be schema_version, meta, entries")
    if document.get("schema_version") != 1:
        errors.append("quality-evaluations.json: schema_version must be 1")
    meta = document.get("meta")
    if not isinstance(meta, dict) or set(meta) != {
            "spec_version", "generated_at", "mode", "entry_count", "candidate_count",
            "route_counts", "verdict_counts", "method"}:
        errors.append("quality-evaluations.json: meta keys are invalid")
    else:
        if meta.get("spec_version") != SPEC_VERSION:
            errors.append(f"quality-evaluations.json: meta.spec_version must be {SPEC_VERSION}")
        if meta.get("mode") != "score":
            errors.append("quality-evaluations.json: meta.mode must be score")
        if not iso_datetime(meta.get("generated_at")):
            errors.append("quality-evaluations.json: meta.generated_at must be ISO-8601")
        if not isinstance(meta.get("method"), str) or not meta["method"].strip():
            errors.append("quality-evaluations.json: meta.method must be nonempty")
    entries = document.get("entries")
    if not isinstance(entries, list):
        return errors + ["quality-evaluations.json: entries must be a list"]
    if isinstance(meta, dict):
        if meta.get("entry_count") != len(entries):
            errors.append("quality-evaluations.json: meta.entry_count does not match entries")
    seen: set[str] = set()
    route_counts: dict[str, int] = {}
    verdict_counts: dict[str, int] = {}
    candidate_count = 0
    for index, entry in enumerate(entries):
        label = f"quality-evaluations.json entries[{index}]"
        if not isinstance(entry, dict) or set(entry) != EVALUATION_KEYS:
            errors.append(f"{label}: keys must be " + ", ".join(sorted(EVALUATION_KEYS)))
            continue
        entry_id = entry["id"]
        if not isinstance(entry_id, str) or not ID_PATTERN.fullmatch(entry_id):
            errors.append(f"{label}: id must be a lowercase hyphenated slug")
        elif entry_id in seen:
            errors.append(f"{label}: duplicate id {entry_id}")
        elif entry_id not in known_ids:
            errors.append(f"{label}: id {entry_id} is neither curated nor a candidate")
        seen.add(entry_id)
        profile = entry["profile"]
        if not isinstance(profile, dict) or set(profile) != PROFILE_KEYS:
            errors.append(f"{label}: profile keys are invalid")
        else:
            if profile.get("entry_id") != entry_id:
                errors.append(f"{label}: profile.entry_id does not match entry id")
            if profile.get("catalog_status") not in {"curated", "candidate"}:
                errors.append(f"{label}: profile.catalog_status must be curated or candidate")
            if profile.get("catalog_status") == "candidate":
                candidate_count += 1
        route = entry["route"]
        if not isinstance(route, dict) or set(route) != ROUTE_KEYS:
            errors.append(f"{label}: route keys are invalid")
        else:
            if route.get("level") not in LEVELS:
                errors.append(f"{label}: route.level is invalid")
            route_counts[route.get("level")] = route_counts.get(route.get("level"), 0) + 1
            if not isinstance(route.get("tools"), list) or not isinstance(route.get("blocked"), list):
                errors.append(f"{label}: route.tools and route.blocked must be lists")
            if not isinstance(route.get("reason"), str) or not route["reason"].strip():
                errors.append(f"{label}: route.reason must be nonempty")
        score_errors = validate_score(entry)
        errors += [f"{label}: {error}" for error in score_errors]
        verdict = (entry.get("score") or {}).get("verdict") if isinstance(entry.get("score"), dict) else None
        if verdict:
            verdict_counts[verdict] = verdict_counts.get(verdict, 0) + 1
    if isinstance(meta, dict):
        if meta.get("candidate_count") != candidate_count:
            errors.append("quality-evaluations.json: meta.candidate_count does not match profiles")
        if meta.get("route_counts") != dict(sorted(route_counts.items())):
            errors.append("quality-evaluations.json: meta.route_counts does not match entries")
        if meta.get("verdict_counts") != dict(sorted(verdict_counts.items())):
            errors.append("quality-evaluations.json: meta.verdict_counts does not match entries")
    return errors


def validate_quality_data(root: Path) -> list[str]:
    candidates_path = root / "data" / "evaluation-candidates.json"
    evaluations_path = root / "data" / "quality-evaluations.json"
    if not candidates_path.exists() and not evaluations_path.exists():
        return []
    errors: list[str] = []
    if not candidates_path.exists() or not evaluations_path.exists():
        return ["quality data: evaluation-candidates.json and quality-evaluations.json must exist together"]
    catalog = []
    for filename in ("rea-resources.json", "tool-resources.json"):
        path = root / "data" / filename
        try:
            catalog.extend(json.loads(path.read_text(encoding="utf-8")))
        except (OSError, json.JSONDecodeError) as error:
            errors.append(f"quality data: cannot read {filename} ({error})")
    curated_ids = {record.get("id") for record in catalog if isinstance(record, dict)}
    candidates = load_json(candidates_path, errors)
    evaluations = load_json(evaluations_path, errors)
    if errors:
        return errors
    errors += validate_candidates(candidates, curated_ids)
    candidate_ids = {entry.get("id") for entry in candidates.get("entries", []) if isinstance(entry, dict)}
    errors += validate_evaluations(evaluations, curated_ids | candidate_ids)
    return errors


def main() -> int:
    root = Path(__file__).resolve().parents[1]
    errors = validate_quality_data(root)
    if errors:
        for error in errors:
            print(error)
        return 1
    print("Quality evaluation data validated.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
